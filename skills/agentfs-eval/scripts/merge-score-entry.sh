#!/usr/bin/env bash
# merge-score-entry.sh — Append a row to the AgentFS score sheet.
#
# Usage:
#   bash merge-score-entry.sh <VERSION> <MODEL> [--template-score N] [--behavioral N/M] [--notes "text"]
#
# Arguments:
#   VERSION          Template version string, e.g. "5.11.1"
#   MODEL            Model name, e.g. "claude-opus-4-6"
#
# Options:
#   --template-score N   Deterministic template quality score (0-100)
#   --behavioral N/M     Behavioral test result, e.g. "3/3"
#   --notes "text"       Free-text notes column
#
# Behaviour:
#   - Score sheet: ~/.agents/skills/agentfs-eval/references/template-scores.md
#   - Always inserts a new row (append-only — never overwrites history)
#   - Newest entries at top (reverse chronological)
#   - Creates the score sheet with correct structure if missing
#
# Exit codes:
#   0 = success, 1 = error

set -euo pipefail

SCORE_FILE="$HOME/.agents/skills/agentfs-eval/references/template-scores.md"

VERSION="${1:?Usage: merge-score-entry.sh <VERSION> <MODEL> [--template-score N] [--behavioral N/M] [--notes \"text\"]}"
MODEL="${2:?Usage: merge-score-entry.sh <VERSION> <MODEL> [--template-score N] [--behavioral N/M] [--notes \"text\"]}"
shift 2

TEMPLATE_SCORE=""
BEHAVIORAL=""
NOTES=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --template-score) TEMPLATE_SCORE="$2"; shift 2 ;;
    --behavioral) BEHAVIORAL="$2"; shift 2 ;;
    --notes) NOTES="$2"; shift 2 ;;
    *) echo "Unknown option: $1" >&2; exit 1 ;;
  esac
done

TODAY="$(date '+%Y-%m-%d %H:%M')"

# ── Create if missing ────────────────────────────────────────────────
if [[ ! -f "$SCORE_FILE" ]]; then
  mkdir -p "$(dirname "$SCORE_FILE")"
  cat > "$SCORE_FILE" << 'HEADER'
# AgentFS Quality Scores

Reverse chronological. Generated by `agentfs-eval`.

| Date | Version | Model | Template Score | Behavioral | Notes |
|------|---------|-------|---------------:|-----------:|-------|
HEADER
  echo "[merge-score] Created $SCORE_FILE"
fi

# ── Always append a new row (newest first) ───────────────────────────
T_SCORE="${TEMPLATE_SCORE:-—}"
B_SCORE="${BEHAVIORAL:-—}"
NEW_ROW="| ${TODAY} | ${VERSION} | ${MODEL} | ${T_SCORE} | ${B_SCORE} | ${NOTES} |"

awk -v new_row="$NEW_ROW" '
  /^\|[-]+\|[-]+\|/ && !inserted {
    print
    print new_row
    inserted = 1
    next
  }
  { print }
' "$SCORE_FILE" > "$SCORE_FILE.tmp"
mv "$SCORE_FILE.tmp" "$SCORE_FILE"
echo "[merge-score] ✓ Added: v${VERSION} / ${MODEL} to $SCORE_FILE"

# ── Post-write integrity check ──────────────────────────────────────
# Ensure header row was not lost during insert
if ! grep -q "^| Date | Version | Model |" "$SCORE_FILE"; then
  sed -i '/^|[-]\+|[-]\+|/i | Date | Version | Model | Template Score | Behavioral | Notes |' "$SCORE_FILE"
  echo "[merge-score] ⚠️  Repaired missing header row" >&2
fi
